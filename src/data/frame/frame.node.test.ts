import { createHash } from "node:crypto";
import { cp, mkdir, mkdtemp, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";

import { format, resolveConfig } from "prettier";
import { describe, expect, it } from "vitest";

const CONTRACT = join(import.meta.dirname, "contract");
const LIMITS = join(import.meta.dirname, "limits.ts");
const PIN = "chartdata.json";
const MODULE = "github.com/cplieger/go/chartdata";
const REPO = "cplieger/go";
const UPSTREAM = "chartdata/contract/";
const SHA = /^[0-9a-f]{40}$/;
const SYNC = process.env["FRAMES_SYNC"] === "1";

/** The tag the contract is vendored at, and the git blob sha of each file. */
interface Pin {
  module: string;
  version: string;
  commit: string;
  files: Record<string, string>;
}

/** chartdata's name for each limit ui reads, in `fixtures/limits.json`, and what it bounds. */
const NAMES = [
  ["MAX_VALUES", "maxValues", "The most values one frame holds, refs and notes included."],
  ["MAX_ROWS", "maxRows", "The most rows a band plot holds, and a calendar's weeks."],
  [
    "MAX_SUB_ROWS",
    "maxSubRows",
    "The most rows a boxes frame's boxes take, one per series in a row.",
  ],
  ["MAX_MAGNITUDE", "maxMagnitude", "The largest magnitude a value may have."],
  ["MAX_CALENDAR_DAYS", "maxCalendarDays", "The most days a calendar frame holds."],
] as const;

function blobSha(bytes: Buffer): string {
  return createHash("sha1").update(`blob ${bytes.length}\0`).update(bytes).digest("hex");
}

/** Every file under `dir` but the pin, as a slash path relative to it. */
async function files(dir: string): Promise<string[]> {
  const entries = await readdir(dir, { recursive: true, withFileTypes: true });
  return entries
    .filter((e) => e.isFile())
    .map((e) =>
      join(e.parentPath, e.name)
        .slice(dir.length + 1)
        .replaceAll("\\", "/"),
    )
    .filter((p) => p !== PIN)
    .sort();
}

function record(v: unknown, what: string): Record<string, unknown> {
  if (typeof v !== "object" || v === null || Array.isArray(v)) {
    throw new TypeError(`${what} is not an object`);
  }
  return v as Record<string, unknown>;
}

/** limits.ts as the sync writes it from the contract's limits and duration ladder fixtures. */
async function limitsSource(limitsJson: string, edgesJson: string): Promise<string> {
  const limits = record(JSON.parse(limitsJson), "limits.json");
  const ladder = record(JSON.parse(edgesJson), "duration-edges.json");
  const lines = [
    "// Code generated by npm run frames:sync from chartdata's contract fixtures. DO NOT EDIT.",
  ];
  for (const [name, key, words] of NAMES) {
    const v = limits[key];
    if (typeof v !== "number" || !Number.isFinite(v)) {
      throw new TypeError(`limits.json: ${key} is not a finite number`);
    }
    lines.push("", `/** ${words} */`, `export const ${name} = ${String(v)};`);
  }
  const edges = ladder["edges"];
  if (
    ladder["unit"] !== "seconds" ||
    !Array.isArray(edges) ||
    edges.some((e) => typeof e !== "number" || !Number.isFinite(e))
  ) {
    throw new TypeError("duration-edges.json: not a list of edges in seconds");
  }
  lines.push(
    "",
    "/** The duration ladder: the bin edges, in seconds, a duration axis and a histogram of waits share. */",
    `export const DURATION_EDGES: readonly number[] = [${edges.join(", ")}];`,
  );
  return format(`${lines.join("\n")}\n`, { ...(await resolveConfig(LIMITS)), filepath: LIMITS });
}

async function readPin(dir: string): Promise<Pin> {
  const pin = record(JSON.parse(await readFile(join(dir, PIN), "utf8")), PIN);
  const files = record(pin["files"], `${PIN} files`);
  if (
    pin["module"] !== MODULE ||
    typeof pin["version"] !== "string" ||
    !/^v\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/.test(pin["version"]) ||
    typeof pin["commit"] !== "string" ||
    !SHA.test(pin["commit"]) ||
    Object.values(files).some((sha) => typeof sha !== "string" || !SHA.test(sha))
  ) {
    throw new TypeError(`${PIN}: not a pin of ${MODULE}`);
  }
  return pin as unknown as Pin;
}

/** What keeps `contract` and `limits` from being the pinned chartdata contract and what the sync writes from it. */
async function drift(contract: string, limits: string): Promise<string[]> {
  let pin: Pin;
  try {
    pin = await readPin(contract);
  } catch (e) {
    return [`${PIN}: ${e instanceof Error ? e.message : String(e)}`];
  }
  const problems: string[] = [];
  const have = await files(contract);
  for (const path of have) {
    const want = pin.files[path];
    if (want === undefined) {
      problems.push(`${path}: not in the pin`);
    } else if (blobSha(await readFile(join(contract, path))) !== want) {
      problems.push(`${path}: differs from chartdata ${pin.version}`);
    }
  }
  for (const path of Object.keys(pin.files)) {
    if (!have.includes(path)) {
      problems.push(`${path}: missing`);
    }
  }
  try {
    const want = await limitsSource(
      await readFile(join(contract, "fixtures", "limits.json"), "utf8"),
      await readFile(join(contract, "fixtures", "duration-edges.json"), "utf8"),
    );
    if ((await readFile(limits, "utf8").catch(() => null)) !== want) {
      problems.push("limits.ts: differs from what frames:sync writes from the contract");
    }
  } catch (e) {
    problems.push(`limits.ts: ${e instanceof Error ? e.message : String(e)}`);
  }
  return problems;
}

async function get(url: string): Promise<Response> {
  const res = await fetch(url);
  if (!res.ok) {
    throw new Error(`${url}: ${String(res.status)} ${res.statusText}`);
  }
  return res;
}

/**
 * Rewrites `contract`, its pin and `limits` to chartdata's contract at the
 * pin's version: the commit the Go module proxy recorded for the tag, each file
 * checked against its blob sha in that commit's tree.
 */
async function sync(contract: string, limits: string): Promise<void> {
  const { version } = record(JSON.parse(await readFile(join(contract, PIN), "utf8")), PIN);
  if (typeof version !== "string") {
    throw new TypeError(`${PIN}: no version`);
  }
  const info = record(
    await (await get(`https://proxy.golang.org/${MODULE}/@v/${version}.info`)).json(),
    "info",
  );
  const origin = record(info["Origin"], `${version}.info Origin`);
  const commit = origin["Hash"];
  if (
    origin["URL"] !== `https://github.com/${REPO}` ||
    origin["Subdir"] !== "chartdata" ||
    typeof commit !== "string" ||
    !SHA.test(commit)
  ) {
    throw new TypeError(`${version}.info: not a commit of ${REPO}'s chartdata`);
  }
  const tree = record(
    await (
      await get(`https://api.github.com/repos/${REPO}/git/trees/${commit}?recursive=1`)
    ).json(),
    "tree",
  );
  if (tree["truncated"] !== false || !Array.isArray(tree["tree"])) {
    throw new TypeError(`${commit}: the tree listing is truncated`);
  }
  const blobs = (tree["tree"] as Record<string, unknown>[])
    .filter((e) => e["type"] === "blob" && String(e["path"]).startsWith(UPSTREAM))
    .map((e) => ({ path: String(e["path"]).slice(UPSTREAM.length), sha: String(e["sha"]) }));
  if (blobs.length === 0 || blobs.some((b) => b.path === PIN)) {
    throw new TypeError(`${commit}: no contract, or a file named ${PIN}`);
  }
  const fetched = await Promise.all(
    blobs.map(async ({ path, sha }) => {
      const url = `https://raw.githubusercontent.com/${REPO}/${commit}/${UPSTREAM}${path}`;
      const bytes = Buffer.from(await (await get(url)).arrayBuffer());
      if (blobSha(bytes) !== sha) {
        throw new Error(`${url}: not blob ${sha}`);
      }
      return { path, bytes };
    }),
  );
  const keep = new Set(blobs.map((b) => b.path));
  for (const path of await files(contract)) {
    if (!keep.has(path)) {
      await rm(join(contract, path));
    }
  }
  for (const { path, bytes } of fetched) {
    await mkdir(dirname(join(contract, path)), { recursive: true });
    await writeFile(join(contract, path), bytes);
  }
  const pin: Pin = {
    module: MODULE,
    version,
    commit,
    files: Object.fromEntries(
      blobs.map((b) => [b.path, b.sha] as const).sort(([a], [b]) => (a < b ? -1 : 1)),
    ),
  };
  await writeFile(join(contract, PIN), `${JSON.stringify(pin, null, 2)}\n`);
  await writeFile(
    limits,
    await limitsSource(
      await readFile(join(contract, "fixtures", "limits.json"), "utf8"),
      await readFile(join(contract, "fixtures", "duration-edges.json"), "utf8"),
    ),
  );
}

describe("the vendored chartdata contract", () => {
  it(
    "is chartdata's contract at the pinned tag, with limits.ts generated from it",
    async () => {
      if (SYNC) {
        await sync(CONTRACT, LIMITS);
      }
      expect(await drift(CONTRACT, LIMITS)).toEqual([]);
    },
    SYNC ? 60_000 : undefined,
  );

  it("generates each limit with chartdata's value", async () => {
    const limits = record(
      JSON.parse(await readFile(join(CONTRACT, "fixtures", "limits.json"), "utf8")),
      "limits.json",
    );
    const ladder = record(
      JSON.parse(await readFile(join(CONTRACT, "fixtures", "duration-edges.json"), "utf8")),
      "duration-edges.json",
    );
    const generated = (await import("./limits.js")) as Record<string, unknown>;
    for (const [name, key] of NAMES) {
      expect(generated[name], name).toBe(limits[key]);
    }
    expect(generated["DURATION_EDGES"]).toEqual(ladder["edges"]);
  });

  it("reports a changed, a missing and an extra file, a stale limits.ts and a broken pin", async () => {
    const dir = await mkdtemp(join(tmpdir(), "ui-frames-"));
    try {
      const contract = join(dir, "contract");
      const limits = join(dir, "limits.ts");
      await cp(CONTRACT, contract, { recursive: true });
      await cp(LIMITS, limits);
      expect(await drift(contract, limits)).toEqual([]);
      await writeFile(join(contract, "frame.ts"), "export {};\n");
      await rm(join(contract, "fixtures", "frame-bins.json"));
      await writeFile(join(contract, "fixtures", "extra.json"), "{}\n");
      await writeFile(limits, "export const MAX_VALUES = 1;\n");
      expect((await drift(contract, limits)).sort()).toEqual([
        "fixtures/extra.json: not in the pin",
        "fixtures/frame-bins.json: missing",
        `frame.ts: differs from chartdata ${(await readPin(CONTRACT)).version}`,
        "limits.ts: differs from what frames:sync writes from the contract",
      ]);
      await writeFile(join(contract, PIN), JSON.stringify({ module: MODULE, version: "dev" }));
      expect(await drift(contract, limits)).toEqual([`${PIN}: ${PIN} files is not an object`]);
    } finally {
      await rm(dir, { recursive: true, force: true });
    }
  });

  it("names a limit chartdata no longer sends", async () => {
    const edges = await readFile(join(CONTRACT, "fixtures", "duration-edges.json"), "utf8");
    await expect(limitsSource(JSON.stringify({ maxValues: 1 }), edges)).rejects.toThrow(
      "limits.json: maxRows is not a finite number",
    );
    await expect(limitsSource("{}", JSON.stringify({ edges: [0, 1], unit: "ms" }))).rejects.toThrow(
      "limits.json: maxValues is not a finite number",
    );
  });

  it("refuses a ladder that is not in seconds", async () => {
    const limits = await readFile(join(CONTRACT, "fixtures", "limits.json"), "utf8");
    await expect(
      limitsSource(limits, JSON.stringify({ edges: [0, 1], unit: "ms" })),
    ).rejects.toThrow("duration-edges.json: not a list of edges in seconds");
  });
});
